"""One-time migration: copy auth_users from the legacy SQLite DB into PostgreSQL.

Usage (from backend/):
    python migrate_to_postgres.py

Reads DATABASE_URL from .env (must be a postgresql+psycopg2:// URL). The source
SQLite file is always backend/database.db. Existing emails are skipped.
"""
import os
from dotenv import load_dotenv
from sqlalchemy import create_engine, text

BACKEND_DIR = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(BACKEND_DIR, ".env"))

SRC = f"sqlite:///{os.path.join(BACKEND_DIR, 'database.db')}"
DST = os.getenv("DATABASE_URL", "")

if not DST.startswith("postgresql"):
    raise SystemExit("Set DATABASE_URL to a postgresql+psycopg2://... URL in backend/.env first.")

src = create_engine(SRC)
dst = create_engine(DST)

with src.begin() as s, dst.begin() as d:
    # Ensure target table exists (same shape as UserRepository).
    d.execute(text("""
        CREATE TABLE IF NOT EXISTS auth_users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email VARCHAR(255) UNIQUE NOT NULL,
            name VARCHAR(255) NOT NULL,
            password_hash VARCHAR(512) NOT NULL,
            role VARCHAR(50) NOT NULL DEFAULT 'user',
            totp_secret VARCHAR(255),
            is_2fa_enabled INTEGER NOT NULL DEFAULT 0,
            is_active INTEGER NOT NULL DEFAULT 1,
            created_at VARCHAR(64) NOT NULL,
            last_login VARCHAR(64)
        )
    """))
    rows = s.execute(text("SELECT * FROM auth_users ORDER BY id")).mappings().all()
    migrated = 0
    for r in rows:
        exists = d.execute(
            text("SELECT id FROM auth_users WHERE email=:e"), {"e": r["email"]}
        ).first()
        if exists:
            continue
        d.execute(
            text("""
                INSERT INTO auth_users
                (id, email, name, password_hash, role, totp_secret, is_2fa_enabled, is_active, created_at, last_login)
                VALUES (:id, :email, :name, :password_hash, :role, :totp_secret, :is_2fa_enabled, :is_active, :created_at, :last_login)
            """),
            dict(r),
        )
        migrated += 1

print(f"Migration complete: {migrated} user(s) copied to PostgreSQL.")